def sections_for(role: str) -> list[dict]:
    """Разделы руководства для этой роли. Порядок как в GUIDE."""

    if role == "admin":
        return [dict(section) for section in GUIDE]

    return [
        dict(section)
        for section in GUIDE
        if section["roles"] == "*" or role in section["roles"]
    ]
