# Получаем ID оборудования по имени
def eq_id(name):
    r = conn.execute("SELECT id FROM equipment WHERE name LIKE ? AND is_active=1 LIMIT 1", (f'%{name}%',)).fetchone()
    if r: return r[0]
    print(f"⚠ Не найдено: {name}")
    return None

def add(equipment_name, work_name, work_type, months, hours, responsible=None):
    eid = eq_id(equipment_name)
    if not eid: return
    cur.execute("""INSERT INTO maintenance_schedule
        (equipment_id, work_name, work_type, months, duration_hours, responsible, year, created_by, created_at)
        VALUES (?,?,?,?,?,?,?,?,?)""",
        (eid, work_name, work_type, months, hours, responsible, YEAR, 'system', datetime.now().strftime('%Y-%m-%d %H:%M:%S')))

