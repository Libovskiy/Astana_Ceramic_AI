def seed():

    init_equipment()

    conn = get_connection()
    cursor = conn.cursor()

    added = 0
    skipped = 0

    for item in EQUIPMENT:

        cursor.execute(
            """
            INSERT OR IGNORE INTO equipment (
                name, type, status, health, readiness,
                location, level, maintenance_required,
                last_check, updated_at, stage
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                item["name"],
                item["type"],
                "Работает",
                100,
                100,
                item["location"],
                "machine",
                0,
                now,
                now,
                item["stage"]
            )
        )

        if cursor.rowcount:
            added += 1
        else:
            skipped += 1

    conn.commit()
    conn.close()

    print(f"Добавлено: {added}")
    print(f"Пропущено (уже существовало): {skipped}")


if __name__ == "__main__":
    seed()
