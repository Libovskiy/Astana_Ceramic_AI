"""
«Производственная цепочка» разворачивается в цех — и не врёт цифрами.

15.10.2026 владелец свёл две сцены в одну: карточка цепочки на
«Главной» открывает «Цех в 3D» — планировку завода со станками из
чек-листов дежурного. Проверяется две вещи, и обе обязательны:

  «кнопка никого не приводит в отказ» — страница открыта всем, кто
  видит «Главную», иначе «Развернуть» ведёт в «нет доступа»;

  парная проверка «посторонних не пускает» — у кого нет ни «Главной»,
  ни обхода, тому закрыт и цех. Без неё первая проверка зелёная и на
  странице, открытой всем подряд.

Отдельно — планировка и честность показаний: участки стоят по
заводским схемам (массаподготовка отдельным корпусом на востоке, печь
и сушилки на западе), живых регистров четыре, при остановленном сборе
чисел на экране нет.

Боевые данные не трогаются: живые запросы идут в песочнице на копии
базы, остальное читается из исходников.

Запуск (из корня проекта): python tests/test_plant_scene.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

from sandbox import Sandbox, check, finish  # ДО импорта backend

from backend.api.main import PAGE_ROLES

PAGE = "/plant-3d"
SCENE = (ROOT / "frontend" / "templates" / "plant_3d.html").read_text(encoding="utf-8")
INDEX = (ROOT / "frontend" / "templates" / "index.html").read_text(encoding="utf-8")


# ─────────────────────────────────────────────────────────
# Кнопка на «Главной» ведёт туда, куда человека пустят
# ─────────────────────────────────────────────────────────

home = set(PAGE_ROLES["/"])
plant = set(PAGE_ROLES[PAGE])
check(
    "все, кто видит цепочку, открывают и цех",
    not (home - plant),
    f"кнопка приведёт в отказ: {sorted(home - plant)}",
)

sb = Sandbox()

for role in ("director", "technologist", "analyst"):
    person = sb.user(role)
    check(f"{role}: видит «Главную»", person.get("/").status_code == 200)
    check(f"{role}: открывает цех", person.get(PAGE).status_code == 200)

# Парная: сцена открыта не всем подряд.
for role in ("worker", "lab_technician"):
    person = sb.user(role)
    check(f"{role}: цех закрыт", person.get(PAGE).status_code == 403)

# Слесарь и электрик «Главной» не видят, но цех им нужен: по нему они
# учат, где что стоит и что в обходе проверять.
for role in ("mechanic", "electrician"):
    person = sb.user(role)
    check(f"{role}: «Главная» закрыта", person.get("/").status_code == 403)
    check(f"{role}: но цех открыт", person.get(PAGE).status_code == 200)


# ─────────────────────────────────────────────────────────
# Как встроен в сводку
# ─────────────────────────────────────────────────────────

check(
    "кнопка стоит в шапке «Производственной цепочки»",
    re.search(r'prod-map-header.*?id="twinExpand"', INDEX, re.S) is not None,
)

check(
    "и разворачивает именно цех",
    "frame.src='/plant-3d?theme=" in INDEX and "embed=1" in INDEX,
)

check(
    "сцена грузится только по нажатию",
    not re.search(r'id="twinFrame"[^>]*\ssrc=', INDEX)
    and "getElementById('twinFrame').removeAttribute('src')" in INDEX,
)

check(
    "в окне нет второго меню и второй шапки",
    ".acai-embed .sidebar" in SCENE and "display:none" in SCENE.split(".acai-embed .sidebar")[1][:120],
)

check(
    "из окна выходят клавишей",
    "acai-twin-close" in SCENE and "acai-twin-close" in INDEX,
)


# ─────────────────────────────────────────────────────────
# Планировка — заводская, а не выдуманная
# ─────────────────────────────────────────────────────────

zones = dict(re.findall(r'\{name:"([^"]+)", x0:(-?[\d.]+)', SCENE))
check("участков на плане одиннадцать", len(zones) == 11, sorted(zones))

check(
    "массаподготовка — отдельным корпусом на востоке",
    zones.get("Массаподготовка") == "72",
    zones.get("Массаподготовка"),
)
check(
    "печь и сушилки — на западе",
    zones.get("Печь обжига") == "-40.5" and zones.get("Сушилка 1") == "-40.5",
    {k: zones.get(k) for k in ("Печь обжига", "Сушилка 1")},
)
check(
    "склад готовой продукции — на улице, южнее корпуса",
    zones.get("Склад ГП") == "5",
    zones.get("Склад ГП"),
)

# Парная: планировку взяли из прежней сцены цепочки, а не придумали
# заново — рамки участков совпадают с ней буква в букву.
TWIN = (ROOT / "frontend" / "templates" / "twin_map.html").read_text(encoding="utf-8")
for name, mark in (("Массаподготовка", "r:[72,33,132,60]"),
                   ("Печь обжига", "r:[-40.5,15.8,-12,25.8]"),
                   ("Склад ГП", "r:[5,61,45,77]")):
    check(f"{name}: рамка та же, что была в цепочке", mark in TWIN, mark)


# ─────────────────────────────────────────────────────────
# Показания: четыре регистра и ни одного выдуманного
# ─────────────────────────────────────────────────────────

check(
    "привязаны те же четыре регистра, что на «Главной»",
    all(key in SCENE for key in ('"pl024_1_загрузка_проц"', '"pl024_2_загрузка_проц"',
                                 '"питатель_1_гц"', '"питатель_2_гц"')),
)

check(
    "имена берутся из справочника регистров",
    "ACAISensors.short(" in SCENE and "/static/sensor-names.js" in SCENE,
)

check(
    "сбор стоит — чисел не показываем вовсе",
    "Показаний нет" in SCENE and "health.ok" in SCENE,
)

check(
    "у станков без регистров цифр не появляется",
    "нет данных" not in SCENE.split("const LIVE_REG")[1][:2000],
    "в строку показаний попало что-то, чего панель не присылает",
)

# ─────────────────────────────────────────────────────────
# Круг вагонеток: три трансбордера и замкнутый путь
# ─────────────────────────────────────────────────────────
# Как это работает на заводе, сказал владелец 16.10.2026: формовка
# грузит → трансбордер 1 на сушилку → трансбордер 2 сзади из сушилки в
# печь → трансбордер 1 из печи на упаковку → трансбордер 3 возвращает
# пустую под формовку. Круг не останавливается.

for tb, mark in (("tb1", "формовка и печь"), ("tb2", "из сушилки в печь"),
                 ("tb3", "возврат под формовку")):
    check(f"{tb}: заведён и подписан по делу",
          f'id:"{tb}"' in SCENE and mark in SCENE, mark)

way = re.search(r"const WAY = \[(.*?)\n\];", SCENE, re.S)
steps = re.findall(r'(?:say|tb):"(\w+|[^"]+)"', way.group(1)) if way else []
check(
    "порядок шага в шаг: сушка, обжиг, разгрузка",
    ["грузят сырец", "front", "сушка", "back", "обжиг", "front", "снимают кирпич", "ret"]
    == [s for s in steps if s in ("грузят сырец", "сушка", "обжиг", "снимают кирпич", "front", "back", "ret")],
    steps,
)

check(
    "путь замкнут: последний шаг возвращает под формовку",
    way and "END.loadX]" in way.group(1).strip().splitlines()[-1],
    way.group(1).strip().splitlines()[-1] if way else "",
)

# Парная: трансбордер один, и если он занят — вагонетка ждёт. Без
# этого вагонетки ездили бы одна сквозь другую.
check(
    "занятый трансбордер заставляет ждать",
    "busy[next.tb]" in SCENE and "w.wait" in SCENE,
    "очередь к тележке не проверяется — вагонетки налезут друг на друга",
)


# ─────────────────────────────────────────────────────────
# Конвейеры идут цепочкой, а не вразнобой
# ─────────────────────────────────────────────────────────

conv = re.search(r"const CONV = \[(.*?)\];", SCENE, re.S)
paths = re.findall(r"\[\[(-?[\d.]+),(-?[\d.]+)\],\s*\[(-?[\d.]+),(-?[\d.]+)\]\]", conv.group(1)) if conv else []
check("конвейеров на схеме больше десяти", len(paths) >= 10, len(paths))

breaks = []
for i in range(len(paths) - 1):
    x1, z1 = float(paths[i][2]), float(paths[i][3])
    x2, z2 = float(paths[i + 1][0]), float(paths[i + 1][1])
    gap = ((x2 - x1) ** 2 + (z2 - z1) ** 2) ** .5
    if gap > 12:                      # больше станка — значит разрыв
        breaks.append((paths[i], paths[i + 1], round(gap, 1)))
check(
    "лента к ленте: между отрезками стоит станок, а не пустота",
    not breaks,
    breaks[:2],
)

finish("Цех в 3D за «Производственной цепочкой»")
